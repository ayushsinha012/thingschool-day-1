SET NOCOUNT ON;
PRINT 'S1F: start ' + CONVERT(VARCHAR, SYSDATETIME(), 121);
BEGIN TRANSACTION;
UPDATE dbo.DeadlockDemo SET Value = Value + 1 WHERE Id = 1;
PRINT 'S1F: locked Id=1 ' + CONVERT(VARCHAR, SYSDATETIME(), 121);
WAITFOR DELAY '00:00:05';
PRINT 'S1F: attempting Id=2 ' + CONVERT(VARCHAR, SYSDATETIME(), 121);
UPDATE dbo.DeadlockDemo SET Value = Value + 1 WHERE Id = 2;
PRINT 'S1F: locked Id=2 ' + CONVERT(VARCHAR, SYSDATETIME(), 121);
COMMIT TRANSACTION;
PRINT 'S1F: committed ' + CONVERT(VARCHAR, SYSDATETIME(), 121);
